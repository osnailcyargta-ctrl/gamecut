          '      O: {m: [[1,1],[1,1]], c: \'#facc15\'},',
          '      S: {m: [[0,1,1],[1,1,0],[0,0,0]], c: \'#4ade80\'},',
          '      T: {m: [[0,1,0],[1,1,1],[0,0,0]], c: \'#c084fc\'},',
          '      Z: {m: [[1,1,0],[0,1,1],[0,0,0]], c: \'#f87171\'}',
