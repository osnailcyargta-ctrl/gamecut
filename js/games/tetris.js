          '      for (let i = g.bag.length - 1; i > 0; i--) {',
          '        const j = game.random.int(0, i);',
          '        const t = g.bag[i]; g.bag[i] = g.bag[j]; g.bag[j] = t;',
          '      }',
          '    }',
          '    return g.bag.pop();',
          '  },',
          '',
          '  spawn(self) {',
          '    const g = game.state;',
          '    const type = this.nextType(self);',
          '    const def = g.pieces[type];',
          '    g.cur = {',
          '      type: type,',
          '      m: def.m.map(row => row.slice()),',
          '      c: def.c,',
          '      x: Math.floor((g.cols - def.m.length) / 2),',
          '      y: -1',
          '    };',
          '    if (this.collides(self, g.cur, 0, 0)) {',
          '      g.over = true;',
          '      game.sound.play(\'lose\');',
          '      game.best(\'tetris\', g.score);',
          '    }',
          '  },',
          '',
          '  collides(self, p, dx, dy) {',
          '    const g = game.state;',
          '    for (let r = 0; r < p.m.length; r++) {',
          '      for (let c = 0; c < p.m[r].length; c++) {',
          '        if (!p.m[r][c]) continue;',
          '        const x = p.x + c + dx, y = p.y + r + dy;',
          '        if (x < 0 || x >= g.cols || y >= g.rows) return true;',
          '        if (y >= 0 && g.board[y][x]) return true;',
          '      }',
          '    }',
          '    return false;',
          '  },',
          '',
          '  rotate(self, m) {',
          '    const n = m.length;',
          '    const res = [];',
          '    for (let r = 0; r < n; r++) {',
          '      res.push([]);',
          '      for (let c = 0; c < n; c++) res[r].push(m[n - 1 - c][r]);',
          '    }',
          '    return res;',
          '  },',
          '',
          '  lock(self) {',
          '    const g = game.state;',
          '    for (let r = 0; r < g.cur.m.length; r++) {',
