          '        if (g.cur.m[r][c]) {',
          '          const y = g.cur.y + r, x = g.cur.x + c;',
          '          if (y >= 0) g.board[y][x] = g.cur.c;',
          '        }',
          '      }',
          '    }',
          '    game.sound.play(\'beep\');',
          '    let cleared = 0;',
          '    for (let r = g.rows - 1; r >= 0; r--) {',
          '      if (g.board[r].every(cell => cell)) {',
          '        g.board.splice(r, 1);',
          '        g.board.unshift(new Array(g.cols).fill(null));',
          '        cleared++;',
          '        r++;',
          '      }',
          '    }',
          '    if (cleared) {',
          '      g.lines += cleared;',
          '      g.score += [0, 100, 300, 500, 800][cleared] * g.level;',
          '      g.level = 1 + Math.floor(g.lines / 10);',
          '      game.sound.play(cleared >= 4 ? \'win\' : \'coin\');',
          '    }',
          '    this.spawn(self);',
          '  },',
          '',
          '  hardDrop(self) {',
          '    const g = game.state;',
          '    let n = 0;',
          '    while (!this.collides(self, g.cur, 0, 1)) { g.cur.y++; n++; }',
          '    g.score += n * 2;',
          '    this.lock(self);',
          '  },',
          '',
          '  onUpdate(self, dt) {',
          '    const g = game.state;',
          '    if (g.over) {',
          '      if (game.input.pressed(\'Enter\')) game.restart();',
          '      return;',
          '    }',
          '    if (game.input.pressed(\'ArrowLeft\') && !this.collides(self, g.cur, -1, 0)) g.cur.x--;',
          '    if (game.input.pressed(\'ArrowRight\') && !this.collides(self, g.cur, 1, 0)) g.cur.x++;',
          '    if (game.input.pressed(\'ArrowUp\')) {',
          '      const rm = this.rotate(self, g.cur.m);',
          '      if (!this.collides(self, {m: rm, x: g.cur.x, y: g.cur.y}, 0, 0)) g.cur.m = rm;',
          '    }',
          '    if (game.input.pressed(\'Space\')) { this.hardDrop(self); return; }',
          '    const interval = Math.max(0.1, 0.65 - (g.level - 1) * 0.06);',
          '    const soft = game.input.down(\'ArrowDown\') ? 0.05 : interval;',
          '    g.acc += dt;',
          '    while (g.acc >= soft) {',
          '      g.acc -= soft;',
          '      if (!this.collides(self, g.cur, 0, 1)) {',
          '        g.cur.y++;',
          '        if (game.input.down(\'ArrowDown\')) g.score += 1;',
          '      } else {',
          '        this.lock(self);',
          '        break;',
          '      }',
          '    }',
          '  },',
          '',
          '  onDraw(self, ctx) {',
          '    const g = game.state;',
          '    const cell = self.width / g.cols;',
          '    ctx.fillStyle = \'#10101c\';',
          '    ctx.fillRect(self.x, self.y, self.width, self.height);',
          '    ctx.strokeStyle = \'rgba(255,255,255,0.06)\';',
          '    ctx.lineWidth = 1;',
          '    ctx.beginPath();',
          '    for (let c = 1; c < g.cols; c++) {',
          '      ctx.moveTo(self.x + c * cell, self.y);',
          '      ctx.lineTo(self.x + c * cell, self.y + self.height);',
          '    }',
          '    for (let r = 1; r < g.rows; r++) {',
          '      ctx.moveTo(self.x, self.y + r * cell);',
          '      ctx.lineTo(self.x + self.width, self.y + r * cell);',
          '    }',
          '    ctx.stroke();',
          '    for (let r = 0; r < g.rows; r++) {',
          '      for (let c = 0; c < g.cols; c++) {',
          '        if (g.board[r][c]) this.cell(ctx, self.x + c * cell, self.y + r * cell, cell, g.board[r][c]);',
          '      }',
          '    }',
          '    if (g.cur && !g.over) {',
          '      for (let r = 0; r < g.cur.m.length; r++) {',
          '        for (let c = 0; c < g.cur.m[r].length; c++) {',
          '          if (g.cur.m[r][c]) {',
          '            const y = g.cur.y + r;',
          '            if (y >= 0) this.cell(ctx, self.x + (g.cur.x + c) * cell, self.y + y * cell, cell, g.cur.c);',
          '          }',
          '        }',
          '      }',
          '    }',
          '    const type = g.bag && g.bag.length ? g.bag[g.bag.length - 1] : \'I\';',
          '    const def = g.pieces[type];',
          '    ctx.fillStyle = \'#a2a2b0\';',
          '    ctx.font = \'bold 15px system-ui, sans-serif\';',
          '    ctx.textAlign = \'left\'; ctx.textBaseline = \'top\';',
          '    ctx.fillText(\'BERIKUTNYA\', 606, 118);',
          '    const pc = 22;',
          '    for (let r = 0; r < def.m.length; r++) {',
          '      for (let c = 0; c < def.m[r].length; c++) {',
          '        if (def.m[r][c]) this.cell(ctx, 612 + c * pc, 145 + r * pc, pc, def.c);',
          '      }',
          '    }',
          '    if (g.over) {',
          '      ctx.fillStyle = \'rgba(10,10,18,0.85)\';',
